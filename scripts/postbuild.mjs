/**
 * Post-build step: writes dist/_headers for Cloudflare Pages.
 *
 * - Computes SHA-256 hashes of every inline <script> Astro produced, so the
 *   Content Security Policy can forbid all other inline scripts.
 * - Adds security headers, cache rules and a noindex header for *.pages.dev
 *   preview addresses.
 * - Fails the build if a secret-looking value has leaked into the output.
 *
 * Run automatically by `npm run build`.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, extname } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

const files = await walk(DIST);
const html = files.filter((f) => extname(f) === '.html');
const hashes = new Set();
const inlineScript = /<script(?![^>]*\bsrc=)(?![^>]*type="application\/ld\+json")[^>]*>([\s\S]*?)<\/script>/g;

for (const f of html) {
  const src = await readFile(f, 'utf8');
  for (const m of src.matchAll(inlineScript)) {
    hashes.add(`'sha256-${createHash('sha256').update(m[1], 'utf8').digest('base64')}'`);
  }
}

// Guard: secrets must never reach the browser bundle.
const secretValues = ['RESEND_API_KEY', 'TURNSTILE_SECRET_KEY']
  .map((k) => process.env[k])
  .filter((v) => typeof v === 'string' && v.length >= 8);
const secretPatterns = [/\bre_[A-Za-z0-9]{20,}/, /service_role/];
for (const f of files.filter((x) => ['.html', '.js', '.css', '.json', '.txt', '.xml', '.webmanifest'].includes(extname(x)))) {
  const src = await readFile(f, 'utf8');
  const leaked = secretValues.some((v) => src.includes(v)) || secretPatterns.some((re) => re.test(src));
  if (leaked) {
    console.error(`postbuild: a secret-looking value was found in ${f.replace(DIST, 'dist/')}. Build stopped. Never expose server secrets to the browser.`);
    process.exit(1);
  }
}

const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(' ')} https://challenges.cloudflare.com https://static.cloudflareinsights.com`.replace(/\s+/g, ' '),
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self' https://cloudflareinsights.com",
  'frame-src https://challenges.cloudflare.com',
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
  'upgrade-insecure-requests',
].join('; ');

const headers = `# Generated by scripts/postbuild.mjs - do not edit dist/_headers by hand.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Strict-Transport-Security: max-age=31536000
  Cross-Origin-Opener-Policy: same-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/brand/*
  Cache-Control: public, max-age=604800

/api/*
  Cache-Control: no-store

# Keep Cloudflare preview addresses out of search results.
https://:project.pages.dev/*
  X-Robots-Tag: noindex

https://:version.:project.pages.dev/*
  X-Robots-Tag: noindex
`;

await writeFile(join(DIST, '_headers'), headers);
console.log(`postbuild: wrote _headers (${hashes.size} inline script hash${hashes.size === 1 ? '' : 'es'}), checked ${files.length} files for secrets`);
